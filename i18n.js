function detectLang() {
  const saved = localStorage.getItem("p72_lang");
  if (saved && I18N[saved]) return saved;
  const raw = (navigator.language || "en").slice(0, 2).toLowerCase();
  return I18N[raw] ? raw : "en";
}

function t(key) {
  const pack = I18N[window.P72_LANG] || I18N.en;
  return pack[key] || I18N.en[key] || key;
}

function applyI18n() {
  document.documentElement.lang = window.P72_LANG || "en";
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  const sel = document.getElementById("langSel");
  if (sel) sel.value = window.P72_LANG;
}

function setLang(code) {
  window.P72_LANG = I18N[code] ? code : "en";
  localStorage.setItem("p72_lang", window.P72_LANG);
  applyI18n();
  if (typeof renderRace === "function") renderRace();
}

window.P72_LANG = detectLang();
document.addEventListener("DOMContentLoaded", applyI18n);
